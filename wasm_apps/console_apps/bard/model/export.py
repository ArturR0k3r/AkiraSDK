"""Quantize a trained Bard GRU and emit a C header.

The input side of the GRU only ever sees one-hot characters, so
W_ih @ emb[c] + b_ih is folded into a per-character table.  Tables and
weights are int8 with one float scale per row; the hidden state is
quantized to int8 (h*127) for the matrix products, exactly as the C code
does, and this script measures the cost of that on held-out text.

usage: export.py model.pt out.h
"""
import sys, numpy as np, torch
ck = torch.load(sys.argv[1], weights_only=False)
sd, chars, H = ck['state'], ck['chars'], ck['H']
V = len(chars)
f = lambda k: sd[k].detach().numpy().astype(np.float64)
emb, Wih, Whh, bih, bhh = f('emb.weight'), f('gru.weight_ih_l0'), f('gru.weight_hh_l0'), f('gru.bias_ih_l0'), f('gru.bias_hh_l0')
Wo, bo = f('out.weight'), f('out.bias')
T = emb @ Wih.T + bih                       # (V, 3H)

def q8(M):
    s = np.abs(M).max(axis=1) / 127.0
    s[s == 0] = 1e-8
    return np.clip(np.round(M / s[:, None]), -127, 127).astype(np.int8), s.astype(np.float32)
Tq, Ts = q8(T); Hq, Hs = q8(Whh); Oq, Os = q8(Wo)

sig = lambda x: 1 / (1 + np.exp(-x))
def run(text, quant):
    h = np.zeros(H); nll = 0.0; idx = [chars.index(c) for c in text]
    for i in range(len(idx) - 1):
        c = idx[i]
        if quant:
            hq = np.clip(np.round(h * 127), -127, 127)
            gh = (Hq.astype(np.float64) @ hq) * Hs / 127.0 + bhh
            t = Tq[c].astype(np.float64) * Ts[c]
        else:
            gh = Whh @ h + bhh; t = T[c]
        r = sig(t[:H] + gh[:H]); z = sig(t[H:2*H] + gh[H:2*H]); n = np.tanh(t[2*H:] + r * gh[2*H:])
        h = (1 - z) * n + z * h
        if quant:
            hq = np.clip(np.round(h * 127), -127, 127)
            lg = (Oq.astype(np.float64) @ hq) * Os / 127.0 + bo
        else:
            lg = Wo @ h + bo
        lg -= lg.max(); p = np.exp(lg) / np.exp(lg).sum()
        nll -= np.log(p[idx[i + 1]] + 1e-12)
    return nll / (len(idx) - 1)
import os
text = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'tinyshakespeare.txt')).read()
val = text[int(0.9 * len(text)):][:6000]
lf, lq = run(val, False), run(val, True)
print(f'H={H} V={V} val loss float {lf:.4f}  int8 {lq:.4f}  (+{100 * (lq - lf) / lf:.2f}%)')

nbytes = Tq.nbytes + Hq.nbytes + Oq.nbytes
print(f'weights {nbytes} bytes int8 + {(Ts.size + Hs.size + Os.size + bhh.size + bo.size) * 4} bytes float')
def carr(name, a, ty, per=16):
    flat = a.reshape(-1)
    fmt = (lambda v: f'{int(v)}') if ty in ('int8_t',) else (lambda v: f'{float(v):.8g}f')
    rows = [', '.join(fmt(v) for v in flat[i:i + per]) for i in range(0, len(flat), per)]
    return f'static const {ty} {name}[{len(flat)}] = {{\n    ' + ',\n    '.join(rows) + '\n};\n'
vocab = ''.join(chars).encode('unicode_escape').decode().replace('"', '\\"')
with open(sys.argv[2], 'w') as o:
    o.write('/* Generated by export.py from a GRU trained on tinyshakespeare.\n')
    o.write(f' * H={H} V={V}, int8 weights with per-row float scales.\n')
    o.write(f' * Held-out loss: float {lf:.4f} nats/char, int8 {lq:.4f}. */\n')
    o.write('#ifndef BARD_MODEL_H\n#define BARD_MODEL_H\n#include <stdint.h>\n')
    o.write(f'#define BARD_V {V}\n#define BARD_H {H}\n#define BARD_LOSS_X1000 {int(lq * 1000)}\n')
    o.write(f'static const char BARD_VOCAB[BARD_V + 1] = "{vocab}";\n')
    o.write(carr('BARD_TBL', Tq, 'int8_t')); o.write(carr('BARD_TBL_S', Ts, 'float', 8))
    o.write(carr('BARD_WHH', Hq, 'int8_t')); o.write(carr('BARD_WHH_S', Hs, 'float', 8)); o.write(carr('BARD_BHH', bhh.astype(np.float32), 'float', 8))
    o.write(carr('BARD_WO', Oq, 'int8_t')); o.write(carr('BARD_WO_S', Os, 'float', 8)); o.write(carr('BARD_BO', bo.astype(np.float32), 'float', 8))
    o.write('#endif\n')
# golden vector for the C test: logits after feeding a fixed prompt through the int8 path
prompt = 'ROMEO:\nWhat light'
h = np.zeros(H)
for ch in prompt:
    c = chars.index(ch); hq = np.clip(np.round(h * 127), -127, 127)
    gh = (Hq.astype(np.float64) @ hq) * Hs / 127.0 + bhh; t = Tq[c].astype(np.float64) * Ts[c]
    r = sig(t[:H] + gh[:H]); z = sig(t[H:2*H] + gh[H:2*H]); n = np.tanh(t[2*H:] + r * gh[2*H:]); h = (1 - z) * n + z * h
hq = np.clip(np.round(h * 127), -127, 127); lg = (Oq.astype(np.float64) @ hq) * Os / 127.0 + bo
np.save(sys.argv[2] + '.golden.npy', lg)
print('golden top5 after', repr(prompt), [(chars[i], round(float(lg[i]), 3)) for i in np.argsort(-lg)[:5]])
