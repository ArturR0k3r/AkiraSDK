/* ═══════════════════════════════════════════════════════════════════════════
 *  Helper: simple memcpy (no stdlib)
 * ═══════════════════════════════════════════════════════════════════════════ */
static void mcpy(void *dst, const void *src, int n) {
    uint8_t *d = (uint8_t *)dst;
    const uint8_t *s = (const uint8_t *)src;
    while (n-- > 0) *d++ = *s++;
}

