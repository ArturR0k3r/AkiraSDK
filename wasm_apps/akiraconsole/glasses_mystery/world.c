/* ═══════════════════════════════════════════════════════════════════════════
 *  World functions
 * ═══════════════════════════════════════════════════════════════════════════ */

void world_load_screen(int screen_id) {
    if (screen_id < 0 || screen_id >= NUM_SCREENS) return;
    current_screen_id = (uint8_t)screen_id;
    const screen_def_t *scr = &world_screens[screen_id];
    rle_decode(scr->rle_data, scr->rle_size, current_tiles, TILES_X * TILES_Y);
}

int world_get_tile(int tx, int ty) {
    if (tx < 0 || tx >= TILES_X || ty < 0 || ty >= MAP_TILES_Y)
        return T_WALL_TOP; /* out of bounds = solid */
    return current_tiles[ty * TILES_X + tx];
}

const door_t *world_find_door(int tile_x, int tile_y) {
    const screen_def_t *scr = &world_screens[current_screen_id];
    for (int i = 0; i < scr->num_doors; i++) {
        if (scr->doors[i].tile_x == tile_x && scr->doors[i].tile_y == tile_y)
            return &scr->doors[i];
    }
    return 0;
}

const npc_spawn_t *world_get_npc_spawns(int *count) {
    const screen_def_t *scr = &world_screens[current_screen_id];
    *count = scr->num_npcs;
    return scr->npc_spawns;
}

const item_spawn_t *world_get_item_spawns(int *count) {
    const screen_def_t *scr = &world_screens[current_screen_id];
    *count = scr->num_items;
    return scr->item_spawns;
}
